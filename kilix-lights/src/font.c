static const uint8_t *glyph_for(unsigned char ch)
{
    if (ch < FONT_FIRST || ch > FONT_LAST) ch = '?';
    return glyphs[ch - FONT_FIRST];
}

bool font_has_glyph(unsigned char ch)
{
    if (ch < FONT_FIRST || ch > FONT_LAST) return false;
    if (ch == ' ') return true;
    const uint8_t *rows = glyph_for(ch);
    for (int y = 0; y < 7; y++)
        if (rows[y] != 0) return true;
    return false;
}

int font_text_width(const char *text)
{
    int width = 0, line = 0;
    if (text == NULL) return 0;
    for (const unsigned char *p = (const unsigned char *)text; *p; p++) {
        if (*p == '\n') {
            if (line > width) width = line;
            line = 0;
        } else {
            line += FONT_ADVANCE;
        }
    }
    return line > width ? line : width;
}

void font_draw(Canvas *c, int x, int y, const char *text, uint32_t rgb)
{
    int pen_x = x, pen_y = y;
    if (c == NULL || c->px == NULL || text == NULL) return;

    for (const unsigned char *p = (const unsigned char *)text; *p; p++) {
        if (*p == '\n') {
            pen_x = x;
            pen_y += FONT_LINE_H;
            continue;
        }
        const uint8_t *rows = glyph_for(*p);
        for (int gy = 0; gy < 7; gy++) {
            for (int gx = 0; gx < FONT_GLYPH_W; gx++) {
                if ((rows[gy] & (uint8_t)(1u << (6 - gx))) == 0) continue;
                draw_px(c, pen_x + gx, pen_y + gy * 2, rgb);
                draw_px(c, pen_x + gx, pen_y + gy * 2 + 1, rgb);
            }
        }
        pen_x += FONT_ADVANCE;
    }
}
