static inline const uint8_t *kilix_glyph_rows(char character)
{
    static const uint8_t blank[7] = {0};
    if (character >= 'a' && character <= 'z')
        character = (char)(character - 'a' + 'A');
    for (size_t index = 0;
         index < sizeof KILIX_GLYPHS / sizeof KILIX_GLYPHS[0]; index++)
        if (KILIX_GLYPHS[index].character == character)
            return KILIX_GLYPHS[index].row;
    return blank;
}

